#!/usr/bin/env python3
"""Build racepath.html: the whole tool as ONE html file that works by double-clicking it.

The page is the same UI as ``racepath serve`` (racepath.web.INDEX_HTML). Instead of the
HTTP API it calls the JavaScript port of racepath (src/racepath/js/racepath.js) through
an in-memory job store (src/racepath/js/jobs.js). No server, no install, no network.

usage:
  python scripts/build_offline_html.py            # writes racepath.html at the repo root
  python scripts/build_offline_html.py -o out.html
  python scripts/build_offline_html.py --check    # fail if racepath.html is not up to date

The output is deterministic (no timestamps), so the committed racepath.html can be
compared with a fresh build in CI. Only the standard library is used.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
JS_DIR = os.path.join(ROOT, "src", "racepath", "js")
DEFAULT_OUT = os.path.join(ROOT, "racepath.html")

NOTICE = ("解析はすべてこのブラウザの中(JavaScript)で行い、ネットリストを外部に送信しません。"
          "結果はページを開いている間だけ保持されます。必要なファイルはダウンロードしてください。")


def _script(code: str) -> str:
    # "</script" would end the inline <script>; "<\/script" means the same in JS strings,
    # template literals and regexes (the engine's report.html template contains a script tag)
    code = code.replace("</script", "<\\/script").replace("</SCRIPT", "<\\/SCRIPT")
    if "<!--" in code:
        raise SystemExit("embedded script contains <!--")
    return f"<script>\n{code}\n</script>"


def render() -> str:
    from racepath import __version__
    from racepath.jobs import DEFAULT_CORNERS
    from racepath.web import INDEX_HTML

    with open(os.path.join(JS_DIR, "racepath.js"), encoding="utf-8") as f:
        engine = f.read()
    with open(os.path.join(JS_DIR, "jobs.js"), encoding="utf-8") as f:
        jobs = f.read()
    if f'var VERSION = "{__version__}";' not in engine:
        raise SystemExit(f"src/racepath/js/racepath.js VERSION does not match racepath {__version__}")

    corners = json.dumps(DEFAULT_CORNERS, ensure_ascii=False)
    backend = "\n".join([
        _script(engine),
        _script(f"window.RACEPATH_DEFAULT_CORNERS = {corners};\n" + jobs + "\nRacepathJobs.install(window);"),
        f'<footer class="note" style="max-width:1100px;margin:0 auto;padding:0 16px 24px">{NOTICE}</footer>',
    ])
    page = INDEX_HTML
    for old, new in (("<title>racepath ローカル</title>", "<title>racepath</title>"),
                     ("<h1>racepath ローカル <span", "<h1>racepath <span"),
                     ("<!--LOCAL_BACKEND-->", backend)):
        if page.count(old) != 1:
            raise SystemExit(f"template marker not found exactly once: {old!r}")
        page = page.replace(old, new)
    page = page.replace("__TOKEN__", "offline").replace("__VERSION__", __version__)
    return page.replace("<!doctype html>", "<!doctype html>\n<!-- racepath " + __version__ +
                        " single-file build: generated by scripts/build_offline_html.py, do not edit -->", 1)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("-o", "--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="exit 1 if the output file differs from a fresh build")
    args = ap.parse_args(argv)
    page = render()
    data = page.encode("utf-8")
    if args.check:
        try:
            with open(args.out, "rb") as f:
                same = f.read() == data
        except OSError:
            same = False
        if not same:
            raise SystemExit(f"{os.path.relpath(args.out, ROOT)} is out of date: run python scripts/build_offline_html.py")
        print(f"{os.path.relpath(args.out, ROOT)} is up to date")
        return
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "wb") as f:
        f.write(data)
    print(f"wrote {args.out} ({len(data) / 1e3:.0f} kB)")


if __name__ == "__main__":
    main()
